def fold(num1, num2):
    """"Сложение двух переменных"""
    result = num1 + num2
    return result

def subtract(num1,num2):
    """"Вычитание двух переменных"""
    result = num1 - num2
    return result

def divide(num1, num2):
    """"Деление двух переменных"""
    result = num1 / num2
    return result

def multiply(num1,num2):
    """"Умножение двух переменных"""
    result = num1 * num2
    return result("operation_history")